"""Single source of truth for when timed workflows run.

`scheduler/crontab.txt` is generated from this (python cli.py crontab), and
`python cli.py due` / the week simulator use the same table. The referee is
invoke-only and is intentionally absent.
"""
from __future__ import annotations

from datetime import datetime

SCHEDULE: dict[str, str] = {
    "reply_monitor": "*/5 * * * *",    # every 5 minutes
    "gift_list": "0 * * * *",          # hourly: ingest wants; birthday cart check
    "date_night": "0 9 * * 1",         # Mondays 09:00
    "friends_crm": "15 * * * *",       # hourly at :15
    "long_shift": "0 7,13 * * *",      # 07:00 and 13:00 daily
    "random_flowers": "0 10 * * *",    # daily 10:00
    "dashboard": "0 19 * * 0",         # Sundays 19:00
}


def _field_match(spec: str, value: int) -> bool:
    for part in spec.split(","):
        if part == "*":
            return True
        if part.startswith("*/"):
            if value % int(part[2:]) == 0:
                return True
            continue
        if "-" in part:
            a, b = (int(x) for x in part.split("-"))
            if a <= value <= b:
                return True
            continue
        if int(part) == value:
            return True
    return False


def cron_matches(expr: str, dt: datetime) -> bool:
    minute, hour, dom, month, dow = expr.split()
    cron_dow = (dt.weekday() + 1) % 7  # cron: 0 = Sunday
    return (_field_match(minute, dt.minute) and _field_match(hour, dt.hour)
            and _field_match(dom, dt.day) and _field_match(month, dt.month)
            and _field_match(dow, cron_dow))


def due(dt: datetime) -> list[str]:
    return [name for name, expr in SCHEDULE.items() if cron_matches(expr, dt)]


def crontab(repo_dir: str, python: str = "python3") -> str:
    lines = [
        "# Relationship Ops — generated by `python cli.py crontab`. Times are in the crontab's local time;",
        "# set CRON_TZ / TZ to match config.yaml `timezone`.",
        "# The argument referee is invoke-only and deliberately has NO entry here.",
    ]
    for name, expr in SCHEDULE.items():
        cmd = "dashboard" if name == "dashboard" else f"run {name}"
        lines.append(f"{expr} cd {repo_dir} && {python} cli.py {cmd} >> logs/cron.log 2>&1")
    return "\n".join(lines) + "\n"
